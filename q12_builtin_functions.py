# Q12: Five built-in functions on a list

data = [45, 12, 78, 23, 56, 9, 34]
print("List:", data)

print("len()    :", len(data))
print("max()    :", max(data))
print("min()    :", min(data))
print("sum()    :", sum(data))
print("sorted() :", sorted(data))
print("reversed():", list(reversed(data)))
